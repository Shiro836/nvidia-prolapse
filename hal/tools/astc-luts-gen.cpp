/* astc-luts-gen: emits the ASTC decoder lookup tables as C data (out/gen/nvhal_astc_luts.c).
 *
 * The tables are computed by Mesa's own code, src/util/texcompress_astc_luts.cpp (Granite::ASTCLutHolder),
 * compiled from the pinned Mesa commit (Makefile MESA_SHA). This generator only replaces Mesa's C wrapper
 * (src/util/texcompress_astc_luts_wrap.cpp, which needs Mesa's generated pipe_format headers): the five
 * LUTs are taken in the wrapper's order with the wrapper's sizes and texel formats, written here as
 * VkFormat values the way vk_texcompress_astc.c converts them (vk_format_from_pipe_format):
 *
 *   color_endpoint          lut[]          sizeof(lut)       PIPE_FORMAT_R16G16B16A16_UINT -> VK_FORMAT_R16G16B16A16_UINT
 *   color_endpoint_unquant  unquant_lut[]  unquant_offset    PIPE_FORMAT_R8_UINT           -> VK_FORMAT_R8_UINT
 *   weights                 lut[]          sizeof(lut)       PIPE_FORMAT_R8G8B8A8_UINT     -> VK_FORMAT_R8G8B8A8_UINT
 *   weights_unquant         unquant_lut[]  unquant_offset    PIPE_FORMAT_R8_UINT           -> VK_FORMAT_R8_UINT
 *   trits_quints            trits_quints[] sizeof(...)       PIPE_FORMAT_R16_UINT          -> VK_FORMAT_R16_UINT
 *
 * plus the 14 partition tables (R8_UINT) in vk_texcompress_astc.c's block-size order
 * (get_partition_table_index / astc_prepare_buffer). The bytes are the host's in-memory
 * representation; the generator refuses to run on a big-endian host (both targets are little-endian).
 *
 * usage: astc-luts-gen OUT.c MESA_SHA */
#include <cstdint>
#include <cstdio>
#include <cstring>

#include "texcompress_astc_luts.h"

/* VkFormat values (vulkan_core.h); the generated file names them symbolically */
static const char *const fmt_r16g16b16a16_uint = "VK_FORMAT_R16G16B16A16_UINT";
static const char *const fmt_r8_uint = "VK_FORMAT_R8_UINT";
static const char *const fmt_r8g8b8a8_uint = "VK_FORMAT_R8G8B8A8_UINT";
static const char *const fmt_r16_uint = "VK_FORMAT_R16_UINT";

static void emit(FILE *f, const char *name, const void *data, size_t size) {
    const unsigned char *p = static_cast<const unsigned char *>(data);
    fprintf(f, "static const uint8_t %s[%zu] = {", name, size);
    for (size_t i = 0; i < size; i++) fprintf(f, "%s%u", i % 32 ? "," : (i ? ",\n" : "\n"), p[i]);
    fprintf(f, "\n};\n");
}

int main(int argc, char **argv) {
    if (argc != 3) {
        fprintf(stderr, "usage: %s OUT.c MESA_SHA\n", argv[0]);
        return 2;
    }
    const uint16_t probe = 1;
    if (*reinterpret_cast<const unsigned char *>(&probe) != 1) {
        fprintf(stderr, "astc-luts-gen: big-endian host; the LUT bytes would not match the little-endian targets\n");
        return 1;
    }
    auto &luts = Granite::get_astc_luts();
    FILE *f = fopen(argv[1], "w");
    if (!f) {
        perror(argv[1]);
        return 1;
    }
    fprintf(f, "/* GENERATED by tools/astc-luts-gen.cpp from Mesa %s src/util/texcompress_astc_luts.cpp\n"
               " * (Granite::ASTCLutHolder). Do not edit. */\n#include \"nvhal_astc.h\"\n\n", argv[2]);
    struct { const char *name; const void *data; size_t size; const char *fmt; } l[5] = {
        {"lut_color_endpoint", luts.color_endpoint.lut, sizeof luts.color_endpoint.lut, fmt_r16g16b16a16_uint},
        {"lut_color_endpoint_unquant", luts.color_endpoint.unquant_lut, luts.color_endpoint.unquant_offset, fmt_r8_uint},
        {"lut_weights", luts.weights.lut, sizeof luts.weights.lut, fmt_r8g8b8a8_uint},
        {"lut_weights_unquant", luts.weights.unquant_lut, luts.weights.unquant_offset, fmt_r8_uint},
        {"lut_trits_quints", luts.integer.trits_quints, sizeof luts.integer.trits_quints, fmt_r16_uint},
    };
    for (auto &e : l) emit(f, e.name, e.data, e.size);
    /* vk_texcompress_astc.c astc_prepare_buffer(): formats[] order = get_partition_table_index() */
    static const unsigned bs[14][2] = {{4, 4},  {5, 4},  {5, 5},  {6, 5},   {6, 6},   {8, 5},   {8, 6},
                                       {8, 8},  {10, 5}, {10, 6}, {10, 8},  {10, 10}, {12, 10}, {12, 12}};
    char name[64];
    size_t sizes[14];
    for (int i = 0; i < 14; i++) {
        auto &t = luts.get_partition_table(bs[i][0], bs[i][1]);
        sizes[i] = (size_t)t.lut_width * t.lut_height;
        if (t.lut_buffer.size() != sizes[i]) {
            fprintf(stderr, "astc-luts-gen: partition table %ux%u: %zu bytes, expected %u x %u\n", bs[i][0], bs[i][1],
                    t.lut_buffer.size(), t.lut_width, t.lut_height);
            return 1;
        }
        snprintf(name, sizeof name, "lut_partition_%ux%u", bs[i][0], bs[i][1]);
        emit(f, name, t.lut_buffer.data(), sizes[i]);
    }
    fprintf(f, "\nconst struct nvhal_astc_lut nvhal_astc_luts[NVHAL_ASTC_NUM_LUTS] = {\n");
    for (auto &e : l) fprintf(f, "    {%s, sizeof %s, %s},\n", e.name, e.name, e.fmt);
    fprintf(f, "};\n\nconst struct nvhal_astc_lut nvhal_astc_partition_tables[NVHAL_ASTC_NUM_PARTITION_TABLES] = {\n");
    for (int i = 0; i < 14; i++)
        fprintf(f, "    {lut_partition_%ux%u, %zu, VK_FORMAT_R8_UINT}, /* %ux%u blocks */\n", bs[i][0], bs[i][1],
                sizes[i], bs[i][0], bs[i][1]);
    fprintf(f, "};\n");
    if (fclose(f)) {
        perror(argv[1]);
        return 1;
    }
    return 0;
}
