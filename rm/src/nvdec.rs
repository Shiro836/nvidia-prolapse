// Descriptor buffer layout per decoded frame (stock 615.71.09 VP9 trace:
// DRV_PIC_SETUP at +0, VP9_SET_TILE_SIZE_BUF +0x200, PROB_TAB_BUF +0x900,
// CTX_COUNTER_BUF +0x1800, NVDEC_STATUS +0x4c00, 0x5000 per frame).
const VP9_TILES: usize = 0x200;
const VP9_PROBS: usize = 0x900;
const VP9_COUNTS: usize = 0x1800;
const VP9_STATUS: usize = 0x4c00;
const VP9_DESC: usize = 0x5000;
// Filter buffer mapping as stock (identical for 640x360 .. 3840x2160):
// INTRA_TOP at +0, VP9_SET_FILTER_BUFFER at +0x10000, 0x4dc at +0xd5c800.
const VP9_FILTER_SIZE: usize = 0xe0_0000;
const VP9_FILTER_OFF: usize = 0x1_0000;
const VP9_4DC_OFF: usize = 0xd5_c800;
const VP9_SEG_SIZE: usize = 0x8_0000;
const VP9_COLMV_SIZE: usize = 0x100_0000;
const VP9_SURFACES: usize = 10;

/// A ring index or reference slot (below 16) as a method offset term or `GP_PUT`.
fn slot_u32(slot: usize) -> u32 {
    u32::try_from(slot).expect("slot and ring indices are small")
}

/// Build the engine's nvdec_vp9_pic_s for a parsed frame (field mapping
/// checked against the stock pic_s of the same streams, see compare-desc).
pub(crate) fn vp9_pic(
    h: &crate::vp9::FrameHeader,
    st: &crate::vp9::Vp9State,
    stream_len: usize,
) -> crate::nvdec_drv::Vp9PicS {
    use crate::nvdec_drv::{Vp9Dims, Vp9PicS};
    let dims = |w: u32, hh: u32| Vp9Dims {
        // nvdec_vp9_pic_s frame sizes and strides are 16-bit fields
        // (nvdec_drv.h): the low 16 bits are what the engine reads.
        width: low_u16(w),
        height: low_u16(hh),
        stride: [low_u16(w.next_multiple_of(64)); 2],
    };
    let mut p = Vp9PicS {
        // nvdec_vp9_pic_s.stream_len is 32 bits (nvdec_drv.h).
        stream_len: low_u32(u64_from_usize(stream_len)),
        gptimer_timeout_value: 0x04d3_f640,
        surface: 1,
        ..Default::default()
    };
    let tile_cols = 1u32 << h.log2_tile_cols;
    let sb_rows = h.height.div_ceil(64);
    p.vp9_bsd_ctrl_offset = 12 * (tile_cols - 1) * sb_rows;
    p.vp9_flt_above_offset = p.vp9_bsd_ctrl_offset + (tile_cols - 1) * sb_rows;
    p.v1_bits = 8 << 1; // bit_depth 8
    if !h.is_intra() {
        for i in 0..3 {
            let (w, hh) = st.slot_size(h.ref_frame_idx[i]);
            p.refs[i] = dims(w, hh);
        }
    }
    p.current = dims(h.width, h.height);
    let last_key = st.last_size.is_some() && st.last_frame_type == crate::vp9::KEY_FRAME;
    let res_change = st.last_size.is_some_and(|s| s != (h.width, h.height));
    p.flags = u8::from(h.frame_type == crate::vp9::KEY_FRAME)
        | u8::from(last_key) << 1
        | u8::from(res_change) << 2
        | u8::from(h.error_resilient) << 3
        | u8::from(st.last_show_frame) << 4
        | u8::from(h.intra_only) << 5;
    p.ref_frame_sign_bias = h.sign_bias;
    // The signed char fields of nvdec_vp9_pic_s (nvdec_drv.h) take the
    // parsed values bit for bit; the syntax limits them to 0..=63.
    p.loop_filter_level = h.filter_level.cast_signed();
    p.loop_filter_sharpness = h.sharpness.cast_signed();
    p.qp_y_ac = h.base_q_idx;
    p.qp_y_dc = h.delta_q_y_dc;
    p.qp_ch_ac = h.delta_q_uv_ac;
    p.qp_ch_dc = h.delta_q_uv_dc;
    p.lossless = i8::from(h.lossless);
    p.transform_mode = h.tx_mode.cast_signed();
    p.allow_high_precision_mv = i8::from(h.allow_high_precision_mv);
    // Ignored for intra frames; stock writes 0 or 4 there depending on the
    // stream (a640: 0, vp9_640x360.webm: 4).
    p.mcomp_filter_type = if h.is_intra() {
        0
    } else {
        h.interp_filter.cast_signed()
    };
    p.comp_pred_mode = h.reference_mode.cast_signed();
    let s = h.sign_bias;
    if !h.is_intra() && (s[2] != s[1] || s[3] != s[1]) {
        p.comp_fixed_ref = h.comp_fixed_ref.cast_signed();
        p.comp_var_ref = [
            h.comp_var_ref[0].cast_signed(),
            h.comp_var_ref[1].cast_signed(),
        ];
    }
    // log2 tile counts are at most 6 (VP9 spec 7.2); the fields are signed chars.
    p.log2_tile_columns = low_u8(h.log2_tile_cols).cast_signed();
    p.log2_tile_rows = low_u8(h.log2_tile_rows).cast_signed();
    let seg = &st.seg;
    p.segment_enabled = u8::from(seg.enabled);
    p.segment_map_update = u8::from(seg.update_map);
    p.segment_map_temporal_update = u8::from(seg.temporal_update);
    p.segment_feature_mode = u8::from(seg.abs_delta);
    for i in 0..8 {
        for j in 0..4 {
            p.segment_feature_enable[i][j] = u8::from(seg.feature_enabled[i][j]);
            p.segment_feature_data[i][j] = seg.feature_data[i][j];
        }
    }
    p.mode_ref_lf_enabled = i8::from(h.mode_ref_delta_enabled);
    p.mb_ref_lf_delta = st.ref_deltas;
    p.mb_mode_lf_delta = st.mode_deltas;
    // Stock writes 9 into the header's `reserved5` byte on every frame
    // (all five traced streams); meaning untraced, kept for parity.
    p.reserved5 = 9;
    p
}

/// Decode IVF packets of a VP9 profile-0 stream through NVDEC: CPU parses
/// headers and maintains probability contexts, the engine decodes, its
/// symbol counts drive backward adaptation for the next frame.
pub fn decode_vp9(device: &Rc<Device>, packets: &[&[u8]]) -> Result<Vp9Report> {
    use crate::nvdec_drv::{Pod, Vp9EntropyCounts};
    use crate::vp9::{Vp9State, split_superframe, tile_sizes};
    let mut ch = VideoChannel::new(device)?;
    let decoder_class = ch.decoder_class;
    let max_packet = packets.iter().map(|p| p.len()).max().unwrap_or(0);
    let (bits_mem, bits) = ch.buffer(round_up(max_packet + 4096, 1 << 16))?;
    let (desc_mem, desc) = ch.buffer(VP9_DESC)?;
    let (_seg_mem, seg) = ch.buffer(2 * VP9_SEG_SIZE)?;
    let (_mv_mem, colmv) = ch.buffer(2 * VP9_COLMV_SIZE)?;
    let (_filter_mem, filter) = ch.buffer(VP9_FILTER_SIZE)?;
    let mut bits_cpu = bits_mem.map()?;
    let mut desc_cpu = desc_mem.map()?;
    let mut st = Vp9State::default();
    let mut surfaces: Vec<(Rc<crate::rm::Memory>, crate::gpu::GpuMapping)> = Vec::new();
    let mut geometry = None::<(usize, usize, usize)>; // stride, chroma_offset, size
    let mut report = Vp9Report {
        decoder_class,
        outputs: Vec::new(),
        frame_times: Vec::new(),
        decoded: 0,
        status_words: Vec::new(),
        descriptors: Vec::new(),
    };
    let (mut seg_flip, mut mv_flip) = (0usize, 0usize);
    let read_surface = |surfaces: &[(Rc<crate::rm::Memory>, crate::gpu::GpuMapping)],
                        i: usize,
                        size: usize|
     -> Result<Vec<u8>> {
        let mut out = vec![0u8; size];
        // Sound only after the GPU handoff: every frame's ch.run (synchronous submit + wait) completed.
        surfaces[i].0.map()?.read_bytes(0, &mut out)?;
        Ok(out)
    };
    for packet in packets {
        for frame in split_superframe(packet)? {
            let h = st.parse(frame)?;
            if st.bit_depth != 8 {
                // The parser accepts profile 2 for the session path; this probe is 8-bit only.
                return Err(Error::Contract(format!(
                    "VP9 {}-bit frame: decode_vp9 handles profile 0 only (use nv_video)",
                    st.bit_depth
                )));
            }
            if h.show_existing_frame {
                let (w, hh) = st.slot_size(h.frame_to_show);
                let (stride, chroma, size) = geometry
                    .ok_or_else(|| Error::Contract("VP9: show_existing before any frame".into()))?;
                let s = st.slot_surface(h.frame_to_show).unwrap_or(0);
                report.outputs.push(Vp9Output {
                    surface: read_surface(&surfaces, s, size)?,
                    width: usize_from_u32(w),
                    height: usize_from_u32(hh),
                    stride,
                    chroma_offset: chroma,
                });
                continue;
            }
            let (w, hh) = (usize_from_u32(h.width), usize_from_u32(h.height));
            let (stride, chroma, size) = *geometry.get_or_insert_with(|| {
                let (w64, h64) = (round_up(w, 64), round_up(hh, 64));
                (
                    w64,
                    w64 * h64,
                    round_up(w64 * h64 + w64 * round_up(hh.div_ceil(2), 64), 1 << 16),
                )
            });
            if round_up(w, 64) > stride || round_up(w, 64) * round_up(hh, 64) > chroma {
                return Err(Error::Contract(format!(
                    "VP9: frame grows to {w}x{hh} beyond the first frame's surfaces (resize unsupported)"
                )));
            }
            if surfaces.is_empty() {
                for _ in 0..VP9_SURFACES {
                    surfaces.push(ch.buffer(size)?);
                }
            }
            let used: Vec<usize> = st.referenced().collect();
            let cur = (0..VP9_SURFACES)
                .find(|i| !used.contains(i))
                .ok_or_else(|| Error::Contract("VP9: no free surface".into()))?;
            // Descriptor: pic_s, tile sizes, probabilities, zeroed counts.
            if std::env::var_os("NVDEC_VP9_DEBUG").is_some() {
                crate::diag::diag!(
                    "vp9 frame {}: type {} show {} intra_only {} err_res {} parallel {} refresh_ctx {} ctx {} reset {} tx_mode {} q {} hdr {}+{} refresh {:#x}",
                    report.decoded,
                    h.frame_type,
                    h.show_frame,
                    h.intra_only,
                    h.error_resilient,
                    h.frame_parallel,
                    h.refresh_frame_context,
                    h.frame_context_idx,
                    h.reset_frame_context,
                    h.tx_mode,
                    h.base_q_idx,
                    h.uncompressed_size,
                    h.header_size,
                    h.refresh_frame_flags
                );
            }
            let pic = vp9_pic(&h, &st, frame.len());
            let mut d = vec![0u8; VP9_DESC];
            d[..256].copy_from_slice(pic.as_bytes());
            for (k, (tw, th)) in tile_sizes(&h).iter().enumerate() {
                d[VP9_TILES + k * 4..VP9_TILES + k * 4 + 2].copy_from_slice(&tw.to_le_bytes());
                d[VP9_TILES + k * 4 + 2..VP9_TILES + k * 4 + 4].copy_from_slice(&th.to_le_bytes());
            }
            let probs = st.entropy_table();
            d[VP9_PROBS..VP9_PROBS + probs.as_bytes().len()].copy_from_slice(probs.as_bytes());
            // Sound only after the GPU handoff: the previous frame's ch.run (synchronous submit + wait) completed.
            desc_cpu.write_bytes(0, &d)?;
            report.descriptors.push(d[..VP9_COUNTS].to_vec());
            // Stock 615.71.09 (a640 key frame, input buffer captured at
            // 0x408): the engine gets the frame from the first tile on, i.e.
            // after the uncompressed and compressed headers, while pic_s
            // stream_len stays the full frame size.
            let tiles = frame
                .get(h.uncompressed_size + h.header_size..)
                .ok_or_else(|| Error::Contract("VP9: headers overrun frame".into()))?;
            // Sound only after the GPU handoff: as the descriptor above.
            bits_cpu.write_bytes(0, tiles)?;
            // Sound only after the GPU handoff: as the descriptor above.
            bits_cpu.write_bytes(tiles.len(), &[0u8; 256])?;

            let da = desc.address();
            let a = |off: usize| low_u32((da + u64_from_usize(off)) >> 8);
            let fa = |off: usize| low_u32((filter.address() + u64_from_usize(off)) >> 8);
            let sva = |i: usize| surfaces[i].1.address();
            let mut words = Vec::new();
            // Stock writes every buffer-offset method as NONINC (offset>>8, 0).
            let addr = |words: &mut Vec<u32>, m: u32, v: &[u32]| {
                words.push(3 << 29 | 2 << 16 | 4 << 13 | m >> 2);
                words.extend_from_slice(&[v[0], 0]);
            };
            method(&mut words, 4, 0x200, &[9]); // SET_APPLICATION_ID VP9
            method(&mut words, 4, 0x400, &[0x52059]); // CONTROL_PARAMS as stock
            addr(&mut words, 0x404, &[a(0)]);
            addr(&mut words, 0x408, &[low_u32(bits.address() >> 8)]);
            for i in 0..3 {
                let s = if h.is_intra() {
                    cur
                } else {
                    st.slot_surface(h.ref_frame_idx[i]).unwrap_or(cur)
                };
                addr(&mut words, 0x430 + 4 * slot_u32(i), &[low_u32(sva(s) >> 8)]);
                method(
                    &mut words,
                    4,
                    0x474 + 4 * slot_u32(i),
                    &[low_u32((sva(s) + u64_from_usize(chroma)) >> 8)],
                );
            }
            addr(&mut words, 0x424, &[a(VP9_STATUS)]);
            method(
                &mut words,
                4,
                0x40c,
                &[low_u32(u64_from_usize(report.decoded))],
            ); // PICTURE_INDEX (32 bits)
            addr(&mut words, 0x5d0, &[a(VP9_TILES)]);
            addr(&mut words, 0x5c0, &[a(VP9_PROBS)]);
            addr(&mut words, 0x5c4, &[a(VP9_COUNTS)]);
            let sega = |k: usize| low_u32((seg.address() + u64_from_usize(k * VP9_SEG_SIZE)) >> 8);
            let mva =
                |k: usize| low_u32((colmv.address() + u64_from_usize(k * VP9_COLMV_SIZE)) >> 8);
            addr(&mut words, 0x5c8, &[sega(seg_flip)]);
            addr(&mut words, 0x5cc, &[sega(1 - seg_flip)]);
            addr(&mut words, 0x5d8, &[mva(mv_flip)]);
            addr(&mut words, 0x5d4, &[mva(1 - mv_flip)]);
            addr(&mut words, 0x5dc, &[fa(VP9_FILTER_OFF)]);
            addr(&mut words, 0x4c8, &[fa(0)]);
            addr(&mut words, 0x4dc, &[fa(VP9_4DC_OFF)]);
            addr(&mut words, 0x43c, &[low_u32(sva(cur) >> 8)]);
            method(
                &mut words,
                4,
                0x480,
                &[low_u32((sva(cur) + u64_from_usize(chroma)) >> 8)],
            );
            method(&mut words, 4, 0x300, &[0]); // EXECUTE
            report.frame_times.push(ch.run(words)?);
            report.decoded += 1;
            let mut counts_raw = vec![0u8; size_of::<Vp9EntropyCounts>()];
            // Sound only after the GPU handoff: ch.run (synchronous submit + wait) above completed this frame.
            desc_cpu.read_bytes(VP9_COUNTS, &mut counts_raw)?;
            let counts = Vp9EntropyCounts::from_bytes(&counts_raw);
            let mut sw = [0u32; 8];
            for (k, w) in sw.iter_mut().enumerate() {
                *w = desc_cpu.read_u32(VP9_STATUS + 4 * k)?;
            }
            report.status_words.push(sw);
            mv_flip ^= 1;
            if st.seg.enabled {
                seg_flip ^= 1;
            }
            st.finish_frame(&h, counts.as_ref(), cur)?;
            if h.show_frame {
                report.outputs.push(Vp9Output {
                    surface: read_surface(&surfaces, cur, size)?,
                    width: w,
                    height: hh,
                    stride,
                    chroma_offset: chroma,
                });
            }
        }
    }
    Ok(report)
}

/// Block-linear (64x8 GOB, 2-GOB blocks) offset of pixel (x, y) in a plane of
/// `stride` bytes; tinygrad extra/hevc/hevc.py `_addr_table`.
pub(crate) fn block_linear_offset(x: usize, y: usize, stride: usize) -> usize {
    let (gob_x, gob_y) = (x / 64, y / 8);
    let base = ((gob_y / 2 * (stride / 64) + gob_x) * 2 + gob_y % 2) * 512;
    let (lx, ly) = (x % 64, y % 8);
    base + ((lx & 0x0f)
        | ((ly & 0x03) << 4)
        | ((lx & 0x10) << 2)
        | ((ly & 0x04) << 5)
        | ((lx & 0x20) << 3))
}

/// Untile a decoded surface to packed NV12 (w x h luma, then interleaved UV).
///
/// # Errors
/// `Contract` when `surface` is too small for the requested size and layout.
pub fn untile_nv12(
    surface: &[u8],
    w: usize,
    h: usize,
    stride: usize,
    chroma_offset: usize,
) -> Result<Vec<u8>> {
    let byte = |offset: usize| {
        surface.get(offset).copied().ok_or_else(|| {
            Error::Contract(format!(
                "untile {w}x{h} (stride {stride}, chroma at {chroma_offset}): offset {offset} \
                 beyond the {}-byte surface",
                surface.len()
            ))
        })
    };
    let mut out = Vec::with_capacity(w * h + w * h.div_ceil(2));
    for y in 0..h {
        for x in 0..w {
            out.push(byte(block_linear_offset(x, y, stride))?);
        }
    }
    for y in 0..h.div_ceil(2) {
        for x in 0..w {
            out.push(byte(chroma_offset + block_linear_offset(x, y, stride))?);
        }
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn block_linear_matches_gob_layout() {
        // First GOB row: 16-byte runs, then rows; x=16 jumps to +64.
        assert_eq!(block_linear_offset(0, 0, 128), 0);
        assert_eq!(block_linear_offset(15, 0, 128), 15);
        assert_eq!(block_linear_offset(0, 1, 128), 16);
        assert_eq!(block_linear_offset(16, 0, 128), 64);
        assert_eq!(block_linear_offset(0, 4, 128), 128);
        assert_eq!(block_linear_offset(32, 0, 128), 256);
        // Second GOB in the block is the next GOB row; next block skips stride.
        assert_eq!(block_linear_offset(0, 8, 128), 512);
        assert_eq!(block_linear_offset(64, 0, 128), 1024);
        assert_eq!(block_linear_offset(0, 16, 128), 2048);
    }
}
