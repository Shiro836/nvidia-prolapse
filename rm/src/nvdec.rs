fn alloc_zeroed(
    device: &Rc<Device>,
    space: &AddressSpace,
    size: usize,
) -> Result<(Rc<crate::rm::Memory>, crate::gpu::GpuMapping)> {
    let memory = device.allocate_vram(size)?;
    let va = space.map(&memory)?;
    if va.address() & 0xff != 0 || va.address() >> 40 != 0 {
        return Err(Error::Contract(
            "NVDEC buffers need 256-byte aligned 40-bit VAs".into(),
        ));
    }
    let mut cpu = memory.map()?;
    let zero = vec![0u8; size.min(1 << 20)];
    let mut off = 0;
    while off < size {
        let n = zero.len().min(size - off);
        // Sound only after the GPU handoff: fresh allocation, zeroed before its VA is handed to any GPU work.
        cpu.write_bytes(off, &zero[..n])?;
        off += n;
    }
    Ok((memory, va))
}

/// An NVDEC channel on our own VA space: TSG on the NVDEC0 runlist, SYNC
/// context share, 0xC96F GPFIFO and the decoder class object. Frames are
/// submitted one at a time and waited on with a host semaphore release.
pub(crate) struct VideoChannel {
    device: Rc<Device>,
    pub space: AddressSpace,
    pub decoder_class: u32,
    ring: crate::rm::Mapping,
    command: crate::rm::Mapping,
    command_va: u64,
    doorbell: crate::rm::Mapping,
    sem_cpu: crate::rm::Mapping,
    sem_va: u64,
    token: u32,
    put: usize,
    cmd_off: usize,
    serial: u32,
    objects: Vec<Rc<Object>>,
    _keep: Vec<Rc<crate::rm::Memory>>,
    _maps: Vec<crate::gpu::GpuMapping>,
}

const ENTRIES: usize = 1024;
/// `NVC9B0_ALLOCATION_PARAMETERS` size, as its `size` field records it.
const DECODER_PARAMS_SIZE: u32 = const_u32_from_usize(size_of::<crate::abi::VideoDecoder>());

impl VideoChannel {
    pub(crate) fn new(device: &Rc<Device>) -> Result<Self> {
        let classes = device.classes()?;
        let decoder_class = DECODER_CLASSES
            .into_iter()
            .find(|c| classes.contains(c))
            .ok_or_else(|| Error::Contract("no NVDEC class exposed by RM".into()))?;
        if !classes.contains(&0xc96f) {
            return Err(Error::Contract(
                "spike assumes Blackwell host class 0xc96f".into(),
            ));
        }
        let space = AddressSpace::new(device)?;
        let (sem_mem, sem) = alloc_zeroed(device, &space, 4096)?;
        let sem_cpu = sem_mem.map()?;
        // Ring/userd + pushbuffer (same layout as gpu::run_check).
        let queue_memory = device.allocate_memory(65536, true)?;
        let command_memory = device.allocate_vram(65536)?;
        let queue_va = space.map(&queue_memory)?;
        let command_va = space.map(&command_memory)?;
        let mut ring = queue_memory.map()?;
        let command = command_memory.map()?;
        let doorbell = device.map_usermode()?;
        for i in 0..65536 / 4 {
            ring.write_u32(i * 4, 0)?;
        }
        // TSG on the NVDEC0 runlist; kernel_channel.c requires channel engine ==
        // TSG engine and takes the VA space from the context share.
        let mut group_params = crate::abi::ChannelGroup {
            vaspace: space.vaspace.handle,
            engine: NV2080_ENGINE_TYPE_NVDEC0,
            ..Default::default()
        };
        let group = Object::new(
            device,
            device.handle,
            0xa06c,
            &mut group_params,
            vec![Rc::clone(&space.vaspace)],
        )?;
        // SYNC subcontext (flags 0): kernel_fifo_gp102.c:144-160 allows ASYNC
        // only on GR/GR-CE; the NVDEC object alloc fails with 0x1f otherwise.
        let mut context_params = crate::abi::ContextShare {
            vaspace: space.vaspace.handle,
            flags: 0,
            subcontext: 0,
        };
        let context = Object::new(
            device,
            group.handle,
            0x9067,
            &mut context_params,
            vec![Rc::clone(&group), Rc::clone(&space.vaspace)],
        )?;
        let mut channel_params = crate::abi::Channel {
            fifo_address: queue_va.address(),
            entries: const { const_u32_from_usize(ENTRIES) },
            context_share: context.handle,
            engine: NV2080_ENGINE_TYPE_NVDEC0,
            ..Default::default()
        };
        channel_params.userd_memory[0] = queue_memory.handle;
        channel_params.userd_offsets[0] = u64_from_usize(ENTRIES * 8);
        let channel = Object::new(
            device,
            group.handle,
            0xc96f,
            &mut channel_params,
            vec![Rc::clone(&group), Rc::clone(&context)],
        )?;
        device.client.compat.require_constant(
            "NV2080_ENGINE_TYPE_NVDEC0",
            u64::from(NV2080_ENGINE_TYPE_NVDEC0),
        )?;
        let mut decoder_params = crate::abi::VideoDecoder {
            size: DECODER_PARAMS_SIZE,
            ..Default::default()
        };
        let decoder = Object::new(
            device,
            channel.handle,
            decoder_class,
            &mut decoder_params,
            vec![Rc::clone(&channel)],
        )?;
        let mut token = 0u32;
        device
            .client
            .control(channel.handle, 0xc36f0108, &mut token)?;
        device
            .client
            .control(group.handle, 0xa06c0101, &mut [1u8, 0, 0])?;
        Ok(Self {
            device: Rc::clone(device),
            space,
            decoder_class,
            ring,
            command,
            command_va: command_va.address(),
            doorbell,
            sem_cpu,
            sem_va: sem.address(),
            token,
            put: 0,
            cmd_off: 0,
            serial: 0,
            // Drop order: decoder, channel, context, group.
            objects: vec![decoder, channel, context, group],
            _keep: vec![sem_mem, queue_memory, command_memory],
            _maps: vec![sem, queue_va, command_va],
        })
    }

    /// Allocate a zeroed VRAM buffer mapped into the channel's VA space.
    pub(crate) fn buffer(
        &self,
        size: usize,
    ) -> Result<(Rc<crate::rm::Memory>, crate::gpu::GpuMapping)> {
        alloc_zeroed(&self.device, &self.space, size)
    }

    /// Submit `words` (subchannel-4 decoder methods ending in EXECUTE),
    /// append a host semaphore release with WFI and wait for it. Returns the
    /// submit-to-release time.
    pub(crate) fn run(&mut self, mut words: Vec<u32>) -> Result<Duration> {
        if self.serial == 0 {
            let mut first = Vec::new();
            method(&mut first, 4, 0, &[self.decoder_class]); // SET_OBJECT
            first.append(&mut words);
            words = first;
        }
        self.serial += 1;
        let serial = self.serial;
        // Host SEM release, WFI, 64-bit payload (clc96f.h SEM_ADDR_LO..EXECUTE).
        let [hi, lo] = hi_lo(self.sem_va);
        method(
            &mut words,
            0,
            0x5c,
            &[lo, hi, serial, 0, 1 | 1 << 20 | 1 << 24],
        );
        if self.cmd_off + words.len() * 4 > 65536 {
            self.cmd_off = 0;
        }
        for (k, w) in words.iter().enumerate() {
            self.command.write_u32(self.cmd_off + k * 4, *w)?;
        }
        let entry = (self.command_va + u64_from_usize(self.cmd_off))
            | (u64_from_usize(words.len()) << 42)
            | (1 << 41);
        self.cmd_off += round_up(words.len() * 4, 256);
        self.ring.write_u32(self.put * 8, low_u32(entry))?;
        self.ring.write_u32(self.put * 8 + 4, high_u32(entry))?;
        self.put = (self.put + 1) % ENTRIES;
        let start = Instant::now();
        crate::platform::device_full_barrier();
        self.ring
            .write_u32(ENTRIES * 8 + 0x8c, slot_u32(self.put))?; // GPPut
        crate::platform::device_full_barrier();
        self.doorbell.write_u32(0x90, self.token)?;
        crate::platform::device_full_barrier();
        let limit = Duration::from_secs(2);
        while self.sem_cpu.read_u32(0)? != serial {
            if start.elapsed() >= limit {
                let gpget = self.ring.read_u32(ENTRIES * 8 + 0x88)?;
                // The channel is torn down by the caller's drop.
                return Err(WaitError::Timeout {
                    operation: "NVDEC submission",
                    object: format!("release {serial} (GPGet {gpget}, put {})", self.put),
                    limit,
                    elapsed: start.elapsed(),
                }
                .into());
            }
            std::thread::sleep(Duration::from_micros(20));
        }
        let elapsed = start.elapsed();
        crate::platform::device_full_barrier();
        Ok(elapsed)
    }
}

impl Drop for VideoChannel {
    fn drop(&mut self) {
        if let Some(group) = self.objects.last() {
            // GPFIFO_SCHEDULE off before the frees; a failure leaves the free
            // below to stop the channel (RM preempts on free), so it is logged.
            if let Err(error) =
                self.device
                    .client
                    .control(group.handle, 0xa06c0101, &mut [0u8, 0, 0])
            {
                crate::diag::diag!("NVDEC channel schedule-off failed: {error}");
            }
        }
        while let Some(o) = self.objects.first().cloned() {
            drop(o);
            self.objects.remove(0);
        }
    }
}

/// Decode `stream` frame by frame (one submission per frame). Returns the
/// raw output surfaces.
pub fn decode_hevc(device: &Rc<Device>, stream: &HevcStream) -> Result<DecodeReport> {
    let mut ch = VideoChannel::new(device)?;
    let decoder_class = ch.decoder_class;

    // Geometry (tinygrad ops_nv.py _ensure_has_vid_hw / encdec).
    let (w64, h64) = (round_up(stream.luma_w, 64), round_up(stream.luma_h, 64));
    let chroma_offset = w64 * h64;
    let surface_size = round_up(
        chroma_offset + w64 * round_up(stream.luma_h.div_ceil(2), 64),
        1 << 16,
    );
    let coloc_size = round_up(h64 * h64 + w64 * h64 / 16, 2 << 20);
    let intra_top_off = h64 * (608 + 4864 + 152 + 2000);
    let blackwell = decoder_class >= 0xcfb0;
    let intra_unk_off = round_up(intra_top_off, 0x10000) + (64 << 10);
    let filter_size = round_up(intra_unk_off + if blackwell { 2 << 20 } else { 0 }, 2 << 20);
    let max_frame = stream.frames.iter().map(|f| f.size).max().unwrap_or(0);
    let bitstream_size = round_up(max_frame + 4096, 1 << 16);
    let desc_size = round_up(stream.descriptors.len(), 4096);

    let (_coloc_mem, coloc) = ch.buffer(coloc_size)?;
    let (_filter_mem, filter) = ch.buffer(filter_size)?;
    let (status_mem, status) = ch.buffer(4096)?;
    let (bits_mem, bits) = ch.buffer(bitstream_size)?;
    let (desc_mem, desc) = ch.buffer(desc_size)?;
    let mut surfaces = Vec::new();
    for _ in stream.frames {
        surfaces.push(ch.buffer(surface_size)?);
    }
    // Sound only after the GPU handoff: fresh descriptor allocation, written before the first submit.
    desc_mem.map()?.write_bytes(0, stream.descriptors)?;
    let mut bits_cpu = bits_mem.map()?;
    let status_cpu = status_mem.map()?;

    let mut slots: [Option<u64>; 16] = [None; 16];
    let mut report = DecodeReport {
        decoder_class,
        surfaces: Vec::new(),
        chroma_offset,
        stride: w64,
        status_words: Vec::new(),
        frame_times: Vec::new(),
    };
    for (i, frame) in stream.frames.iter().enumerate() {
        let data = stream
            .bitstream
            .get(frame.offset..frame.offset + frame.size)
            .ok_or_else(|| Error::Contract("frame outside bitstream".into()))?;
        let desc_off = i * 0x300;
        if desc_off + 0x300 > stream.descriptors.len() || frame.pos >= 16 {
            return Err(Error::Contract("frame descriptor/slot out of range".into()));
        }
        // Sound only after the GPU handoff: the previous frame's ch.run (synchronous submit + wait) completed.
        bits_cpu.write_bytes(0, data)?;
        // Sound only after the GPU handoff: as above.
        bits_cpu.write_bytes(data.len(), &[0u8; 256])?;
        let out_va = surfaces[i].1.address();
        let mut words = Vec::new();
        let d = low_u32((desc.address() + u64_from_usize(desc_off)) >> 8);
        let chroma = u64_from_usize(chroma_offset);
        // Buffer offsets in 256-byte units, added to the 32-bit FILTER_BUFFER field.
        let intra_top = low_u32(u64_from_usize(intra_top_off >> 8));
        let intra_unk = low_u32(u64_from_usize(intra_unk_off >> 8));
        let f = low_u32(filter.address() >> 8);
        method(&mut words, 4, 0x200, &[7]); // SET_APPLICATION_ID HEVC
        // SET_CONTROL_PARAMS: codec HEVC, gptimer, err_conceal, mbtimer,
        // event_trace_logging, testrun_env PROD_RUN.
        method(
            &mut words,
            4,
            0x400,
            &[7 | 1 << 4 | 1 << 6 | 1 << 13 | 1 << 16 | 1 << 18],
        );
        method(&mut words, 4, 0x404, &[d, low_u32(bits.address() >> 8)]); // DRV_PIC_SETUP, IN_BUF_BASE
        slots[usize_from_u32(frame.pos)] = Some(out_va);
        for (slot, va) in slots.iter().enumerate() {
            if let Some(va) = va {
                let slot = slot_u32(slot) * 4;
                method(&mut words, 4, 0x430 + slot, &[low_u32(va >> 8)]);
                method(&mut words, 4, 0x474 + slot, &[low_u32((va + chroma) >> 8)]);
            }
        }
        method(&mut words, 4, 0x414, &[low_u32(coloc.address() >> 8)]); // COLOC_DATA
        method(&mut words, 4, 0x424, &[low_u32(status.address() >> 8)]); // NVDEC_STATUS
        method(&mut words, 4, 0x584, &[d + 2, f]); // HEVC TILE_SIZES, FILTER_BUFFER
        method(&mut words, 4, 0x4c8, &[f + intra_top]); // INTRA_TOP_BUF
        if blackwell {
            method(&mut words, 4, 0x4dc, &[f + intra_unk]);
        }
        method(&mut words, 4, 0x300, &[0]); // EXECUTE
        report.frame_times.push(ch.run(words)?);
        let mut st = [0u32; 8];
        for (k, s) in st.iter_mut().enumerate() {
            *s = status_cpu.read_u32(k * 4)?;
        }
        report.status_words.push(st);
        if !frame.is_hist {
            slots[usize_from_u32(frame.pos)] = None;
        }
        let mut out = vec![0u8; surface_size];
        // Sound only after the GPU handoff: every frame's ch.run (synchronous submit + wait) completed.
        surfaces[i].0.map()?.read_bytes(0, &mut out)?;
        report.surfaces.push(out);
    }
    Ok(report)
}

